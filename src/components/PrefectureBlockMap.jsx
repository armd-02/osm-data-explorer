/**
 * 47 prefectures are selectable without any geographic API request.
 * Only the returned code is used; municipality geometry and search BBOX
 * continue to come from municipalities.json (OpenStreetMap-derived data).
 */
export default function PrefectureBlockMap({ selectedCode = '', availableCodes = [], onSelect }) {
  const [zoomed, setZoomed] = React.useState(false)
  const available = new Set(availableCodes.map(code => String(code).padStart(2, '0')))
  const normalizedSelected = String(selectedCode).padStart(2, '0')

  return (
    <div className="rounded-xl border border-slate-200 bg-white p-2">
      <div className="flex flex-wrap items-center justify-between gap-2 mb-2">
        <p className="text-xs text-slate-600">
          都道府県のブロックをクリック・タップして選択
        </p>
        <button
          type="button"
          aria-pressed={zoomed}
          onClick={() => setZoomed(value => !value)}
          className="text-xs text-primary-700 underline underline-offset-2 min-h-[36px] px-2 rounded focus-visible:outline focus-visible:outline-2 focus-visible:outline-primary-700"
        >
          {zoomed ? '日本全体を見る' : '拡大して選ぶ'}
        </button>
      </div>
      <div className="overflow-x-auto overscroll-x-contain" aria-label="都道府県の選択図">
        <svg
          xmlns="http://www.w3.org/2000/svg"
          viewBox="-5 -5 290 260"
          className={zoomed
            ? 'block w-[680px] h-auto max-w-none mx-auto'
            : 'block w-full max-w-[680px] h-auto mx-auto'}
          role="group"
          aria-label="47都道府県から選択するブロック図"
        >
          <path
            d="M0,150 L27,150 A3,3 0 0 0 30,147 L30,120"
            fill="none"
            stroke="#666"
            strokeWidth="0.8"
            pointerEvents="none"
          />
          {PREFECTURE_BLOCKS.map(([code, name, x, y, width, height, color, lx, ly, label]) => {
            const enabled = available.has(code)
            const selected = normalizedSelected === code
            return (
              <g
                key={code}
                role="button"
                tabIndex={enabled ? 0 : -1}
                aria-label={name}
                aria-pressed={selected}
                aria-disabled={!enabled}
                onClick={() => enabled && onSelect(code)}
                onKeyDown={e => {
                  if (!enabled || (e.key !== 'Enter' && e.key !== ' ')) return
                  e.preventDefault()
                  onSelect(code)
                }}
                style={{ cursor: enabled ? 'pointer' : 'not-allowed' }}
              >
                <title>{name}</title>
                <rect
                  x={x} y={y} width={width} height={height} rx={3}
                  fill={selected ? '#4ecdc4' : color}
                  stroke={selected ? '#0f766e' : '#fff'}
                  strokeWidth={selected ? 2 : 1.5}
                  opacity={enabled ? 1 : 0.35}
                />
                <text
                  x={lx} y={ly} dy="0.4em"
                  textAnchor="middle" fontFamily='"Hiragino Sans", "Yu Gothic", "Noto Sans JP", sans-serif'
                  fontSize="10" fontWeight="bold" fill="#222"
                  stroke="#fff" strokeWidth="1.2" strokeLinejoin="round"
                  paintOrder="stroke"
                  pointerEvents="none"
                >{label}</text>
              </g>
            )
          })}
        </svg>
      </div>
      <p className="mt-2 text-[11px] text-slate-500">
        {zoomed
          ? '拡大中です。左右にスクロールするとほかの都道府県を選べます。'
          : '小さなブロックは「拡大して選ぶ」を押してください。'}
      </p>
      <p className="mt-1 text-[11px] text-slate-500">
        ※ 都道府県を選ぶための略図です。実際の検索範囲は選択した市区町村のデータを使用します。
      </p>
    </div>
  )
}
